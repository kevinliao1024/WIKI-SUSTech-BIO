import assert from 'node:assert/strict';
import { createEditReplay } from '../static/onetake/edit-replay.mjs';

const events=new Map();
globalThis.innerHeight=800;
globalThis.window={scrollY:30000,addEventListener(type,fn){events.set(type,fn);},scrollTo({top}){this.scrollY=top;}};
const makeButton=()=>({hidden:true,addEventListener(type,fn){this.click=fn;}});
const start=makeButton(),skip=makeButton();
const root={dataset:{},querySelector(selector){return selector==='[data-edit-start]'?start:skip;}};
const story={getBoundingClientRect(){return {top:6000-window.scrollY,height:20800};}};
const replay=createEditReplay({root,story,toProgress:x=>x,enabled:true,autoStart:false});
for(const take of [.71,.798,.83,1]) assert.equal(replay.update(take,.05),null,'direct project navigation never triggers automatic replay while progress settles');
assert.equal(start.hidden,false);
start.click();
for(let i=0;i<30;i++) replay.update(.55,.05);
assert.equal(root.dataset.editReplay,'placement');
assert.equal(window.scrollY,17000,'RNA return includes the 6000px journey opening');
for(let i=0;i<5;i++) replay.update(.55,.05);
assert.equal(window.scrollY,17000,'the story offset remains stable across frames');
replay.setReady(true);
events.get('wheel')({deltaY:100,preventDefault(){}});
for(let i=0;i<250 && root.dataset.editReplay!=='return';i++) replay.update(.55,.05);
assert.equal(root.dataset.editReplay,'return');
assert.equal(window.scrollY,25100,'completed editing skips directly to the project without crossing CGC or AD chapters');
let forwardPrevented=false;
events.get('wheel')({deltaY:100,preventDefault(){forwardPrevented=true;}});
assert.equal(forwardPrevented,true);
events.get('touchstart')({touches:[{clientY:700}]});
events.get('touchmove')({target:{closest(){return null;}},touches:[{clientY:500}],preventDefault(){}});
events.get('keydown')({key:'ArrowDown',preventDefault(){}});
assert.equal(replay.update(.955,.05).phase,'return','continued forward gestures cannot expose old chapters');
assert.equal(window.scrollY,25100);
skip.click();
assert.equal(window.scrollY,25100,'skip reaches the project in the offset story');
assert.equal(root.dataset.editReplay,undefined);
console.log('Passed direct-anchor entry, story offset, direct project return and forward wheel/touch/key continuity without repeated CGC or AD chapters.');
