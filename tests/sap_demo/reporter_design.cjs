const assert=require('node:assert/strict');
const engine=require('../../static/sap-demo/reporter-engine.js'),vector=require('../../static/sap-demo/reporter-vector.js');
const fs=require('fs'),crypto=require('crypto');let checks=0;
const check=fn=>{fn();checks++;};
const input={text:'GACATGGAGGACGTGCGC',target:16,footprint:12,spacer:2,name:'APOE'};
const prepare=overrides=>engine.prepare({...input,...overrides});
const p=prepare(),r=engine.build(p,'CGA',vector);
check(()=>assert.equal(r.valid,true));
check(()=>assert.deepEqual([p.padding,p.start,p.end,p.recognitionStart,p.recognitionEnd],[1,1,18,2,13]));
check(()=>assert.equal(r.core,'GACATGGAGGACGTGCGA'));
check(()=>assert.deepEqual(r.changes,[{input_position:18,from:'C',to:'A'}]));
check(()=>assert.deepEqual(r.oligos.map(o=>o.sequence),['CAGCGACATGGAGGACGTGCGA','TGCCTCGCACGTCCTCCATGTC']));
check(()=>assert.equal(engine.translate(r.core),'DMEDVR'));
check(()=>assert.equal(r.editedCore,'GACATGGAGGACGTGTGA'));
check(()=>assert.equal(r.assembled.length,7477));
check(()=>assert.equal(p.candidates[0].codon,'CGA'));
check(()=>assert.deepEqual(engine.sites(vector.sequence,true).map(s=>s.position),[2617,2648]));
const old=engine.build(prepare({text:'ATGGAGGACGTGCGC',target:13,footprint:10}),'CGA',vector);
const fixture=JSON.parse(fs.readFileSync(require('node:path').join(__dirname,'fixtures/universal_ev_assemblies.json'))),golden=fixture.products;
check(()=>assert.equal(vector.source_sha256,fixture.source_file_sha256));
check(()=>assert.equal(crypto.createHash('sha256').update(vector.sequence).digest('hex'),fixture.vector_sequence_sha256));
check(()=>assert.equal(vector.sequence.length,7498));
check(()=>assert.equal(vector.cdsEnd-vector.cdsStart,2022));
check(()=>assert.equal(old.oligos[0].sequence,'CAGCATGGAGGACGTGCGA'));
check(()=>assert.equal(crypto.createHash('sha256').update(old.assembled).digest('hex'),golden[0].sequence_sha256));
check(()=>assert.equal(crypto.createHash('sha256').update(old.editedAssembled).digest('hex'),golden[1].sequence_sha256));
for(const [product,expected] of [[r.assembled,golden[2]],[r.editedAssembled,golden[3]]])check(()=>assert.equal(crypto.createHash('sha256').update(product).digest('hex'),expected.sequence_sha256));
for(const [protein,expected] of [[old.protein,golden[0]],[old.editedProtein,golden[1]],[r.protein,golden[2]],[r.editedProtein,golden[3]]])check(()=>assert.equal(crypto.createHash('sha256').update(protein).digest('hex'),expected.protein_sha256));
check(()=>assert.equal(engine.parse('>rna\nacgu\n').sequence,'ACGT'));
for(const bad of ['>a\nACG\n>b\nCGT','ACGT123','<script>',''])check(()=>assert.throws(()=>engine.parse(bad)));
for(const bad of [{target:1},{target:17},{target:16.5},{target:''},{target:19},{spacer:-1},{footprint:0},{footprint:61},{text:'ACATGGAGGACGTGCGC',target:15},{text:'GACATGGAGGACGTGC',target:16},{text:'GACATNGAGGACGTGCGC'}])check(()=>assert.throws(()=>prepare(bad)));
check(()=>assert.equal(prepare({text:input.text+'N'}).original,p.original));
const stop=engine.build(prepare({text:'TAAATGGAGGACGTGCGC'}),'CGA',vector);
check(()=>assert.equal(stop.valid,false));
check(()=>assert.equal(stop.checks.find(c=>c.label==='No premature stop in WT').pass,false));
const site=engine.build(prepare({text:'GGTCTCGAGGACGTGCGC'}),'CGA',vector);
check(()=>assert.equal(site.checks.find(c=>c.label==='No BsaI sites in the full assembled plasmid').pass,false));
check(()=>assert.equal(engine.sites('TCTCAAAAGG',true).length,1));
check(()=>assert.throws(()=>engine.build(p,'GCC',vector)));
for(const footprint of [4,10,12,14,30,60])for(const spacer of [0,2,3,30]){
 const n=footprint+spacer,extra=(3-n%3)%3,up='A'.repeat(n+extra),q=prepare({text:up+'CAG',target:up.length+1,footprint,spacer}),b=engine.build(q,'CAG',vector);
 check(()=>assert.equal(b.valid,true));check(()=>assert.equal(b.core.length%3,0));check(()=>assert.equal(b.core.slice(extra,-3),'A'.repeat(n)));
}
console.log(`PASS: ${checks} sequence checks, Universal EV full-vector golden hashes, default PUF12 frame, parameter ranges and input rejection.`);
