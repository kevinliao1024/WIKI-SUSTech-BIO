import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.WIKI_BASE_URL || 'http://127.0.0.1:8156';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const part = () => page.locator('[data-engineering-workspace]').getAttribute('data-engineering-active-part');
const row = level => page.locator(`[data-engineering-heading-row="${level}"]`);
const expect = async id => page.waitForFunction(id => document.querySelector('[data-engineering-workspace]').dataset.engineeringActivePart === id, id);
await mkdir('work/engineering-rollers-qa', { recursive: true });
try {
  await page.goto(`${base}/engineering#pod`, { waitUntil: 'networkidle' });
  await expect('pod');
  await row('part').locator('[data-engineering-preview="next"]').click();
  await expect('cetus');
  assert.equal(new URL(page.url()).hash, '#cetus');
  const box = await row('part').boundingBox();
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 - box.width * .42, box.y + box.height / 2, { steps: 12 });
  assert.equal(await part(), 'cetus', 'Dragging must not swap the article before release.');
  await page.mouse.up();
  await expect('integrated-orca');
  await page.keyboard.press('ArrowRight');
  await page.waitForTimeout(250);
  assert.equal(await part(), 'integrated-orca', 'Module wheel stops at the group boundary.');
  await row('group').focus();
  await page.keyboard.press('ArrowRight');
  await expect('gfa');
  await page.keyboard.press('ArrowRight');
  await expect('deliver');
  assert.equal(await row('part').getAttribute('aria-disabled'), 'true');
  await page.goBack();
  await expect('gfa');
  await row('group').focus();
  await page.keyboard.press('Home');
  await expect('fundamental-research');
  assert.equal(await row('part').getAttribute('aria-disabled'), 'true');
  await page.keyboard.press('ArrowRight');
  await expect('pod');
  await row('part').focus();
  await page.keyboard.press('ArrowLeft');
  await page.waitForTimeout(250);
  assert.equal(await part(), 'pod');
  await page.screenshot({ path: 'work/engineering-rollers-qa/desktop.png' });
  await row('group').focus();
  await page.keyboard.press('End');
  await expect('functional-validation');
  assert.equal(await row('part').getAttribute('aria-disabled'), 'true');
  await page.keyboard.press('ArrowLeft');
  await expect('model-rna-seq');
  await page.screenshot({ path: 'work/engineering-rollers-qa/long-label.png' });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await row('part').focus();
  await page.keyboard.press('End');
  await expect('model-whole-body');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'work/engineering-rollers-qa/mobile.png' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.goto(`${base}/engineering#pod-cycle-01`, { waitUntil: 'networkidle' });
  await page.locator('[data-engineering-cycle="02"]').click();
  assert.equal(new URL(page.url()).hash, '#pod-cycle-02');
  await page.locator('[data-dbtl-stage="test"]').click();
  assert.equal(new URL(page.url()).hash, '#pod-cycle-02-test');
  const touchPage = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  touchPage.on('pageerror', error => errors.push(error.message));
  await touchPage.goto(`${base}/engineering#pod`, { waitUntil: 'networkidle' });
  const touchRow = touchPage.locator('[data-engineering-heading-row="part"]');
  const bounds = await touchRow.boundingBox();
  const cdp = await touchPage.context().newCDPSession(touchPage);
  const x = bounds.x + bounds.width * .75, y = bounds.y + bounds.height / 2;
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] });
  for (let i = 1; i <= 8; i++) await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - bounds.width * .4 * i / 8, y }] });
  assert.equal(await touchPage.locator('[data-engineering-workspace]').getAttribute('data-engineering-active-part'), 'pod');
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await touchPage.waitForFunction(() => document.querySelector('[data-engineering-workspace]').dataset.engineeringActivePart === 'cetus');
  await touchPage.close();
  assert.deepEqual(errors, []);
  console.log('PASS: click, drag/release commit, endpoints, category/module sync, singleton lock, browser back, keyboard, reduced motion and mobile width.');
} finally { await browser.close(); }
