// PLAYWRIGHT_MODULE may point to an existing Playwright installation.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir, writeFile} from 'node:fs/promises';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.EXPERIMENTS_BASE || 'http://127.0.0.1:8136';
const output = process.env.EXPERIMENTS_OUTPUT || '/tmp/orca-experiments-qa';
await mkdir(output, {recursive:true});
const browser = await chromium.launch({channel:'chrome', headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors = [], pdfRequests = [];
page.on('pageerror', e => errors.push(e.message));
page.on('request', r => { if(r.url().includes('/experiments/pdf/')) pdfRequests.push(r.url()); });
const count = () => page.locator('[data-protocol]:visible').count();
const shot = async name => { await page.waitForTimeout(800); await page.screenshot({path:`${output}/${name}.png`}); };
await page.goto(`${base}/experiments`);
await page.locator('[data-panel="home"]').waitFor({state:'visible'});
assert.equal(await count(),0,'Initial page is an overview, not the protocol list');
assert.equal(await page.locator('.exp-home-card').count(),8);
assert.equal(pdfRequests.length,0);
await shot('desktop');
await page.locator('.exp-guide-entry').click();
assert.equal(await page.locator('[data-panel="guide"]').isVisible(),true);
assert.equal(await page.locator('.exp-guide-section').count(),5);
assert.equal(await count(),0);
await shot('how-to-read');
await page.locator('.exp-guide a[href="#MX01"]').first().click();
await page.waitForSelector('[data-reader][open] iframe');
assert.match(await page.locator('[data-reader-meta]').innerText(),/MX01/);
await page.locator('[data-reader-close]').click();
assert.equal(await page.locator('[data-panel="guide"]').isVisible(),true);
assert.equal(await page.locator('iframe').count(),0);
await page.locator('[data-category="M"]').click();
assert.equal(await count(),13);
const cards = await page.locator('[data-protocol]:visible').evaluateAll(nodes=>nodes.map(n=>({parts:[...n.children].map(c=>c.tagName),text:n.innerText,rect:n.getBoundingClientRect().toJSON()})));
assert.ok(cards.every(c=>JSON.stringify(c.parts)==='["SPAN","H3"]'),'Card face has only the ID and name');
assert.ok(cards[0].rect.y===cards[1].rect.y && cards[0].rect.x!==cards[1].rect.x,'Cards form a grid');
assert.ok(cards.every(c=>!c.text.includes('Version')&&!c.text.includes('Preview')&&!c.text.includes('KB')));
await shot('protocol-cards');
await page.locator('[data-category="RP"]').click();
assert.equal(await count(),6);
await page.locator('[data-search]').fill('flow');
assert.equal(await count(),1);
assert.equal(await page.locator('[data-protocol]:visible').getAttribute('id'),'RP06');
await page.locator('#RP06').focus();await page.keyboard.press('Enter');
await page.waitForSelector('[data-reader][open] iframe');
await page.locator('[data-reader-close]').click();
assert.equal(await page.locator('[data-search]').inputValue(),'flow','Preserve search after viewing PDF');
assert.equal(await count(),1);
assert.equal(await page.locator('#RP06').evaluate(e=>e===document.activeElement),true,'Restore keyboard focus');
await page.locator('[data-search]').fill('no-such-protocol');
assert.equal(await count(),0);
assert.equal(await page.locator('[data-empty]').isVisible(),true);
await page.locator('[data-clear]').click();assert.equal(await count(),36);
await page.locator('[data-category="C"]').click();assert.equal(await count(),4);
await page.goBack();await page.waitForFunction(()=>document.querySelector('[data-category="all"]').hasAttribute('aria-current'));assert.equal(await count(),36);
await page.locator('[data-search]').fill('ABETA42');assert.equal(await count(),1);
await page.goto(`${base}/experiments#MX02`);
await page.waitForSelector('[data-reader][open] iframe');
assert.match(await page.locator('[data-reader] iframe').getAttribute('src'), /MX02_.*\.pdf#view=FitH$/);
await page.waitForTimeout(1600);await shot('pdf-preview');
await page.keyboard.press('Escape');
assert.equal(await page.locator('[data-reader]').isVisible(),false);
assert.equal(await page.locator('iframe').count(),0);
await page.locator('[data-category="home"]').click();
assert.equal(await page.locator('[data-panel="home"]').isVisible(),true);
await page.goBack();await page.waitForFunction(()=>!document.querySelector('[data-panel="library"]').hidden);
for (const width of [834,390,320]) {
  await page.setViewportSize({width,height:900});
  await page.goto(`${base}/experiments`);
  await page.locator('[data-panel="home"]').waitFor({state:'visible'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`No overview overflow at ${width}px`);
  await shot(`home-${width}`);
  await page.locator('.exp-home-card[href="#category-MX"]').click();
  assert.equal(await count(),2);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`No grid overflow at ${width}px`);
  await shot(`cards-${width}`);
  await page.locator('#MX01').click();await page.waitForSelector('[data-reader][open] iframe');
  assert.ok(await page.locator('[data-reader]').evaluate(e=>e.getBoundingClientRect().right<=innerWidth+1),`Viewer fits ${width}px`);
  await page.locator('[data-reader-close]').click();
  await page.locator('[data-category="guide"]').click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`No guide overflow at ${width}px`);
}
const nojs = await browser.newPage({javaScriptEnabled:false});await nojs.goto(`${base}/experiments`);
assert.equal(await nojs.locator('[data-protocol]:visible').count(),36);
assert.equal(await nojs.locator('[data-protocol][href$=".pdf"]').count(),36,'All cards link directly to PDFs without JS');
assert.deepEqual(errors,[]);
await writeFile(`${output}/results.json`,JSON.stringify({passed:true,checks:['overview is the initial view; eight category entry cards','How to read with working protocol links','ID and title only; rectangular card grid','search/filter/empty state/reset/history navigation','modal PDF, keyboard access, focus restore and resource cleanup','834 / 390 / 320px responsive overview, grid, guide and viewer','36 original PDF links without JavaScript'],errors},null,2));
await browser.close();console.log('Experiment browser checks passed.');
