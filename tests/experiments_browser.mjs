// PLAYWRIGHT_MODULE may point to an existing Playwright installation.
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir, writeFile} from 'node:fs/promises';
const require = createRequire(import.meta.url);
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.EXPERIMENTS_BASE || 'http://127.0.0.1:8136';
const output = process.env.EXPERIMENTS_OUTPUT || '/tmp/orca-experiments-qa';
await mkdir(output, {recursive:true});
const browser = await chromium.launch({channel:'chrome', headless:true});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors = [], failedResources = [];
page.on('pageerror', e => errors.push(e.message));
page.on('response', r => {if(r.status()>=400 && r.url().includes('/experiments/')) failedResources.push(r.url());});
const count = () => page.locator('[data-protocol]:visible').count();
const shot = async name => {await page.screenshot({path:output+'/'+name+'.png'});};
const guide=page.locator('.exp-guide');
await page.goto(base+'/experiments');
await page.locator('[data-search-tools]:visible').waitFor();
assert.equal(await count(),36);
assert.equal(await guide.getAttribute('open'),null);
assert.equal(await page.locator('h1').innerText(),'Experiment.');
assert.equal(await page.locator('[data-category]').count(),8); // All + seven peers
assert.equal(await page.locator('.exp-find-steps>li').count(),4);
assert.equal(await page.locator('.exp-read-modules>li').count(),9);
assert.equal(await page.locator('iframe').count(),0);
assert.ok(await page.locator('[data-search]').evaluate(e=>e.getBoundingClientRect().top<innerHeight));
await shot('desktop-collapsed');
const summary=guide.locator('summary');
await summary.focus();
const before=await page.evaluate(()=>scrollY);
await page.keyboard.press('Enter');
assert.equal(await guide.getAttribute('open'),'');
assert.ok(Math.abs(await page.evaluate(()=>scrollY)-before)<2,'No accordion scroll jump');
assert.equal(await page.getByText('Not every experiment needs every section.',{exact:true}).isVisible(),true);
const steps=await page.locator('.exp-find-steps>li').evaluateAll(ns=>ns.map(n=>n.getBoundingClientRect().toJSON()));
assert.equal(steps[0].y,steps[1].y);assert.ok(steps[2].y>steps[0].y);
await shot('guide-desktop');
await page.locator('.exp-read-guide').screenshot({path:output+'/guide-nine-modules.png'});
await page.locator('.exp-guide-opening').click();
assert.equal(await guide.getAttribute('open'),'');
await summary.focus();await page.keyboard.press('Space');
assert.equal(await guide.getAttribute('open'),null);
await page.locator('[data-category="M"]').click();assert.equal(await count(),15);
const cards=await page.locator('[data-protocol]:visible').evaluateAll(ns=>ns.map(n=>({parts:[...n.children].map(c=>c.tagName),rect:n.getBoundingClientRect().toJSON()})));
assert.ok(cards.every(c=>JSON.stringify(c.parts)==='["SPAN","H3"]'));
assert.equal(cards[0].rect.y,cards[1].rect.y);
await page.locator('[data-search]').fill('PrimeSTAR');
assert.ok(await count()>0,'Keywords from source text are indexed');
assert.ok(await page.locator('#M01').isVisible());
await page.locator('[data-category="C"]').click();assert.equal(await count(),0);
assert.equal(await page.locator('[data-search]').inputValue(),'PrimeSTAR','Category changes preserve query');
await page.locator('[data-category="M"]').click();
const filtered=await count();
await summary.click();await summary.click();
assert.equal(await page.locator('[data-search]').inputValue(),'PrimeSTAR');
assert.equal(await count(),filtered);
await page.locator('#M01').focus();await page.keyboard.press('Enter');
await page.waitForSelector('[data-reader][open] iframe');
const reader=page.frameLocator('[data-reader] iframe');
await reader.locator('#procedure').waitFor();
const toc=await reader.locator('nav a').evaluateAll(ns=>ns.map(n=>n.hash.slice(1)));
const headings=await reader.locator('h2').evaluateAll(ns=>ns.map(n=>n.id));
assert.deepEqual(toc,headings);
assert.ok(!toc.includes('workflow'),'No invented optional section');
await reader.getByRole('link',{name:'Materials & Equipment',exact:true}).click();
assert.ok(await reader.locator('#materials-equipment').evaluate(e=>Math.abs(e.getBoundingClientRect().top-20)<4));
await shot('reader-desktop');
await page.locator('[data-reader-close]').click();
assert.equal(await page.locator('[data-search]').inputValue(),'PrimeSTAR');
assert.equal(await page.locator('#M01').evaluate(e=>e===document.activeElement),true);
assert.equal(await page.locator('iframe').count(),0);
await page.locator('[data-reset]').click();assert.equal(await count(),36);
await page.goto(base+'/experiments#RP06');
await page.frameLocator('iframe').locator('#procedure').waitFor();
assert.equal(await page.locator('[data-reader-measurement]').isVisible(),true);
assert.ok(await page.frameLocator('iframe').locator('img').count()>0);
assert.ok(await page.frameLocator('iframe').locator('img').evaluateAll(ns=>ns.every(n=>n.complete&&n.naturalWidth>0)));
await page.locator('[data-reader-close]').click();
await page.goto(base+'/experiments#MX02');
await page.frameLocator('iframe').locator('#procedure').waitFor();
assert.match(await page.locator('iframe').getAttribute('src'),/entries\/MX02\/index.html$/);
await page.keyboard.press('Escape');
assert.equal(await page.locator('[data-reader]').isVisible(),false);
await page.locator('[data-category="all"]').click();
await page.locator('[data-category="C"]').click();
await page.goBack();
await page.waitForFunction(()=>document.querySelector('[data-category="all"]').hasAttribute('aria-current'));
assert.equal(await count(),36);
for (const width of [834,390,320]) {
  await page.setViewportSize({width,height:900});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(base+'/experiments');
  await page.locator('[data-search-tools]:visible').waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'No library overflow at '+width);
  await shot('library-'+width);
  await summary.click();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),'No guide overflow at '+width);
  if(width<760) {
    const bounds=await page.locator('.exp-find-steps>li').evaluateAll(ns=>ns.map(n=>n.getBoundingClientRect().toJSON()));
    assert.ok(bounds[1].y>bounds[0].y);
  }
  await shot('guide-'+width);
  await summary.click();
  await page.locator('#M02').click();
  const small=page.frameLocator('iframe');
  await small.locator('#procedure').waitFor();
  assert.ok(await small.locator('html').evaluate(e=>e.scrollWidth<=innerWidth+1),'No reader overflow at '+width);
  await small.locator('a[href="#troubleshooting"]').click();
  await small.locator('img').first().waitFor();
  assert.ok(await small.locator('img').evaluateAll(ns=>ns.every(n=>n.complete&&n.naturalWidth>0)));
  await shot('reader-'+width);
  await page.locator('[data-reader-close]').click();
}
const nojs=await browser.newPage({javaScriptEnabled:false});
await nojs.goto(base+'/experiments');
assert.equal(await nojs.locator('[data-protocol][href$=".pdf"]:visible').count(),36);
await nojs.locator('summary').click();
assert.equal(await nojs.locator('.exp-read-modules>li:visible').count(),9);
assert.deepEqual(errors,[]);assert.deepEqual(failedResources,[]);
await writeFile(output+'/results.json',JSON.stringify({passed:true,checks:['exact 4 + 9 guide copy; native collapsed accordion; Enter and Space; no scroll jump','seven peer categories, combined source-keyword search, filter/query preservation','36 ID/name cards, HTML reader, actual-section TOC, PDF originals, images and references','focus return, Escape, history and no-JavaScript fallback','1440 / 834 / 390 / 320 px and reduced motion'],errors,failedResources},null,2));
await browser.close();console.log('Experiment browser checks passed.');
